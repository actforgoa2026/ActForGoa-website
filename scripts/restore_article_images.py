"""Reconnect original article photography from the existing crawl, without re-crawling.

Run with the crawl virtualenv. Source images remain unchanged in archive/assets.
The frontend uses WordPress's own medium/large variants when archived.
"""
import gzip, hashlib, json, re, shutil
from pathlib import Path
from urllib.parse import urljoin, urlsplit
from bs4 import BeautifulSoup
ROOT=Path(__file__).resolve().parents[1]
# Managed worktrees share the existing crawl archive in the original checkout.
ARCHIVE=ROOT if (ROOT/'archive/assets').exists() else Path('/Users/zakkrevitt/code/ActForGoa')
manifest={x['url']:x for x in json.load(gzip.open(ROOT/'data/fetch-manifest.json.gz'))}
wp=json.loads((ROOT/'data/wordpress.json').read_text())
rows={f"wp-{x['id']}":x for endpoint in ['wp/v2/posts','wp/v2/portfolio','wp/v2/pages'] for x in wp[endpoint]}
media=wp['wp/v2/media']; byurl={x['source_url']:x for x in media}
byid={x['id']:x for x in media}
by_path={}
for item in media:
    by_path[urlsplit(item['source_url']).path]=item
    for size in item.get('media_details',{}).get('sizes',{}).values():
        if size.get('source_url'):
            byurl[size['source_url']]=item
            by_path[urlsplit(size['source_url']).path]=item
records=json.loads((ROOT/'data/catalog.json').read_text())
pixel_dimensions=json.loads((ROOT/'data/article-image-dimensions.json').read_text()) if (ROOT/'data/article-image-dimensions.json').exists() else {}
provenance={};missing=[]
def local_image(source, alt=''):
    source=urljoin('https://actforgoa.org/',source).split('?')[0]
    if '/wp-content/uploads/' not in source or not re.search(r'\.(jpe?g|png|webp|gif)$',source,re.I):return None
    item=byurl.get(source) or by_path.get(urlsplit(source).path,{})
    if item: source=item['source_url']
    sizes=item.get('media_details',{}).get('sizes',{})
    # Use the largest archived WordPress rendition up to 1600px, never invent a URL.
    variants=[x for x in sizes.values() if 700 <= x.get('width',0) <=1600 and x.get('source_url') in manifest]
    variants.sort(key=lambda x:x['width'],reverse=True)
    chosen=variants[0].get('source_url') if variants else source
    entry=manifest.get(chosen) or manifest.get(source)
    if not entry or not entry.get('path') or not (ARCHIVE/entry['path']).is_file():
        missing.append(source);return None
    path=ARCHIVE/entry['path']; digest=hashlib.sha256(path.read_bytes()).hexdigest()
    dest=ROOT/'public/assets/articles'/(digest[:20]+path.suffix.lower())
    dest.parent.mkdir(exist_ok=True,parents=True)
    if not dest.exists():shutil.copyfile(path,dest)
    result={'src':'/'+str(dest.relative_to(ROOT/'public')),'source':source,'alt':alt or BeautifulSoup(item.get('alt_text',''),'lxml').get_text(' ',strip=True)}
    dimensions=next((size for size in sizes.values() if size.get('source_url')==entry['url']),item.get('media_details',{}))
    if dimensions.get('width') and dimensions.get('height'):
        result.update(width=dimensions['width'],height=dimensions['height'])
    result.update(pixel_dimensions.get(result['src'],{}))
    provenance[result['src']]={'source':source,'rendition':entry['url'],'archivePath':entry['path'],'sha256':digest,'retrievedAt':entry['fetched_at']}
    return result
for record in records:
    if record['kind'] not in ['story','resource']:continue
    row=rows.get(record['id']);content=row.get('content',{}).get('rendered','') if row else ''
    if not content:
        response=manifest.get(record['source'])
        if response and response.get('path') and (ARCHIVE/response['path']).is_file():
            soup=BeautifulSoup((ARCHIVE/response['path']).read_text(errors='replace'),'lxml')
            content=str(soup.select_one('.blog-post .content-container') or soup.select_one('.content-container') or '')
    candidates=[]
    if record['imageSource']:candidates.append((record['imageSource'],''))
    soup=BeautifulSoup(content,'lxml')
    for img in soup.select('img'):
        src=img.get('data-lazyload') or img.get('data-src') or img.get('src','')
        if src:candidates.append((src,img.get('alt','')))
    for gallery in re.findall(r'\[gallery[^\]]*ids="([\d,]+)"',content):
        for ident in gallery.split(','):
            item=byid.get(int(ident),{})
            if item.get('source_url'):candidates.append((item['source_url'],item.get('alt_text','')))
    images=[];seen=set()
    for source,alt in candidates:
        image=local_image(source,alt)
        if image and image['src'] not in seen:
            images.append(image);seen.add(image['src'])
    if images:
        record['image']=images[0]['src'];record['imageSource']=images[0]['source'];record['images']=images
# Remove only unreferenced files generated by this script.
for file in (ROOT/'public/assets/articles').iterdir():
    if '/'+str(file.relative_to(ROOT/'public')) not in provenance:file.unlink()
# Copy the same records to both catalogues: phone values and prose are unchanged.
(ROOT/'data/catalog.json').write_text(json.dumps(records,ensure_ascii=False,separators=(',',':')))
(ROOT/'public/data/catalog.json').write_text(json.dumps(records,ensure_ascii=False,separators=(',',':')))
(ROOT/'data/record-image-map.json').write_text(json.dumps({r['id']:{'image':r['image'],'imageSource':r['imageSource'],'images':r['images']} for r in records if r.get('images')},ensure_ascii=False,indent=2))
(ROOT/'data/article-image-map.json').write_text(json.dumps(provenance,ensure_ascii=False,indent=2))
report={'recordsWithImages':sum(bool(r.get('images')) for r in records),'uniqueFiles':len(provenance),'galleryPlacements':sum(len(r.get('images',[])) for r in records),'missingSources':sorted(set(missing))}
(ROOT/'reports/article-image-restoration.json').write_text(json.dumps(report,indent=2))
print(json.dumps({**report,'missingSources':len(report['missingSources'])},indent=2))
